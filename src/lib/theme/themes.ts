function rgb(red: number, green: number, blue: number, alpha =1): string {
 return `rgb(${red} ${green} ${blue} / ${Math.round(alpha *10000) /100}%)`
}

function shadow(input: {
 x: number
 y: number
 blur: number
 alpha: number
 spread?: number
}): string {
 return `${input.x}px ${input.y}px ${input.blur}px${
 input.spread ? ` ${input.spread}px` : ""
 } ${rgb(0,0,0, input.alpha)}`
}

