const THEMES = new Map<ThemeStyle, ThemeDefinition>(
 THEME_DEFINITIONS.map((theme) => [theme.id, theme]),
)

function getThemeDefinition(id: ThemeStyle): ThemeDefinition {
 return THEMES.get(id) ?? THEME_DEFINITIONS[0]!
}

function isThemeStyle(value: unknown): value is ThemeStyle {
 return (
 value === "default" ||
 value === "minecraft" ||
 value === "material" ||
 value === "windows" ||
 value === "nord" ||
 value === "sunset" ||
 value === "forest" ||
 value === "monochrome"
 )
}

